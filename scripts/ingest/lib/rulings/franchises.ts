export const OWN_IP: Set<string> = new Set(ENTRIES.filter((e) => e.value.franchise == null).map((e) => e.seriesId));

/** franchise id → the row + its members, derived from the entries */
export const FRANCHISES: Record<string, Franchise> = (() => {
  const out: Record<string, Franchise> = {};
  for (const e of ENTRIES) {
    const id = e.value.franchise;
    if (id == null) continue;
    const f = (out[id] ??= { title: '', base: null, members: [] });
    f.members.push(e.seriesId);
    if (e.value.title) { f.title = e.value.title; f.titleNative = e.value.titleNative; f.note = e.value.note; }
    if (e.value.base) f.base = e.seriesId;
  }
  return out;
})();

/** the map's own integrity — the healer refuses a map with problems, the test asserts none (fail closed, P6) */
export function franchiseMapProblems(): string[] {
  const problems: string[] = [];
  const seen = new Map<string, number>();
  for (const e of ENTRIES) seen.set(e.seriesId, (seen.get(e.seriesId) ?? 0) + 1);
  for (const [id, n] of seen) if (n > 1) problems.push(`${id}: ${n} entries (one series → one franchise)`);
  for (const [id, f] of Object.entries(FRANCHISES)) {
    if (!f.title) problems.push(`${id}: no member carries the title`);
    if (!f.base) problems.push(`${id}: no member is the base`);
    if (f.base && !f.members.includes(f.base)) problems.push(`${id}: base ${f.base} is not a member`);
    if (f.members.length < 2) problems.push(`${id}: a franchise of one is NULL, not a row (${f.members.join(', ')})`);
    if (ENTRIES.filter((e) => e.value.franchise === id && e.value.title).length > 1) problems.push(`${id}: more than one member carries a title`);
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(id)) problems.push(`${id}: not a slug (I1)`);
  }
  return problems;
}

// Bundle the edge-function runners into self-contained deploy artifacts.
// scripts/ingest/lib stays the single source of truth; the artifacts under
// supabase/functions/<name>/index.ts are GENERATED — never edit them.
//   npx tsx scripts/ingest/build-functions.ts

import { build } from 'esbuild';
import { readdirSync } from 'node:fs';
import { libHash } from './lib-hash';

const SRC = 'supabase/functions/_src';

async function main() {
  const hash = libHash(); // T2.6 / P4: stamped so system-census can prove the bundles are current
  for (const file of readdirSync(SRC).filter((f) => f.endsWith('.ts'))) {
    const name = file.replace(/\.ts$/, '');
    await build({
      entryPoints: [`${SRC}/${file}`],
      outfile: `supabase/functions/${name}/index.ts`,
      bundle: true,
      format: 'esm',
      platform: 'browser',
      target: 'esnext',
      external: ['node:*'],
      banner: { js: `// GENERATED by scripts/ingest/build-functions.ts — do not edit. lib-hash: ${hash}` },
      logLevel: 'warning',
    });
    console.log(`built supabase/functions/${name}/index.ts`);
  }
}
main();
